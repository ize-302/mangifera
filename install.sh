#!/bin/bash
# mangifera installer for Arch Linux: packages, stow links, SDDM theme.
#
#   ./install.sh                 install
#   ./install.sh --dry-run       print what it would do, change nothing
#   ./install.sh --no-packages   skip installing packages
#   ./install.sh --yes           don't ask to back up the system first
#
# Files in the way are moved to ~/.mangifera-backup-<time>/.
set -e

cd "$(dirname "${BASH_SOURCE[0]}")"

dry=
yes=
packages=1
for arg in "$@"; do
  case "$arg" in
  --dry-run) dry=1 ;;
  # Backing up is the default now; kept so old commands still work
  --backup) ;;
  --no-packages) packages= ;;
  -y | --yes) yes=1 ;;
  -h | --help)
    sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    echo "Unknown option: $arg (see --help)" >&2
    exit 1
    ;;
  esac
done

say() { echo "[+] $*"; }
note() { echo "[!] $*"; }
run() {
  if [ -n "$dry" ]; then
    echo "    would run: $*"
  else
    "$@"
  fi
}

repo_packages=(
  # Compositor; jq parses mmsg output; wlr-randr turns the laptop screen off
  mangowm jq wlr-randr
  # Shell, bar, lock, wallpaper; socat calls the launcher daemon
  quickshell qt6-5compat socat waybar swayidle swaylock swaybg
  # Screenshots, recording and the clipboard; qt6-multimedia shows the
  # webcam (CameraWidget.qml)
  grim slurp satty wf-recorder qt6-multimedia qt6-multimedia-ffmpeg
  wl-clipboard cliphist
  # Portals: wlr for screen sharing, gtk for the rest
  xdg-desktop-portal xdg-desktop-portal-wlr xdg-desktop-portal-gtk
  # Sound, media keys, brightness (libpulse has pactl, paplay);
  # noise-suppression-for-voice is the "Noise Canceling" mic's RNNoise
  pipewire pipewire-pulse wireplumber libpulse playerctl brightnessctl
  noise-suppression-for-voice
  sound-theme-freedesktop
  libnotify
  # Network, Bluetooth; gcc builds src/bluetooth-agent.c
  networkmanager nm-connection-editor bluez bluez-utils blueman
  gcc pkgconf
  alacritty tmux btop fastfetch
  # File manager, thumbnailers, archive and media tag plugins
  thunar gvfs tumbler ffmpegthumbnailer poppler-glib webp-pixbuf-loader libgsf
  thunar-archive-plugin xarchiver thunar-media-tags-plugin
  # tpm
  git
  # Theme, icons, cursor, fonts
  adw-gtk-theme papirus-icon-theme adwaita-cursors adwaita-fonts
  ttf-jetbrains-mono-nerd noto-fonts-emoji glib2 gsettings-desktop-schemas
  # Login screen
  sddm qt6-wayland rsync
  stow
)
[ "$(id -u)" -ne 0 ] || { note "Run this as your own user, not root: it asks for sudo itself."; exit 1; }
command -v pacman >/dev/null || { note "mangifera is for Arch Linux (no pacman here)."; exit 1; }
[ -n "$dry" ] && say "Dry run: nothing will be changed."

if [ -z "$dry" ] && [ -z "$yes" ]; then
  note "This installs packages, upgrades the system, replaces your login"
  note "screen and links over your desktop configs. Back up your system"
  note "first (e.g. a timeshift or snapper snapshot)."
  read -rp "    Continue? [y/N] " answer || answer=
  case "$answer" in
  [yY] | [yY][eE][sS]) ;;
  *)
    say "Nothing was changed."
    exit 1
    ;;
  esac
fi

# --- Packages ---------------------------------------------------------------

if [ -n "$packages" ]; then
  missing=()
  for p in "${repo_packages[@]}"; do
    pacman -Q "$p" >/dev/null 2>&1 || missing+=("$p")
  done
  if [ ${#missing[@]} -gt 0 ]; then
    say "Installing ${#missing[@]} packages: ${missing[*]}"
    # -Syu: Arch doesn't support installing onto an out-of-date system
    run sudo pacman -Syu --needed "${missing[@]}"
  else
    say "Packages: all installed."
  fi
fi

command -v stow >/dev/null || { note "stow isn't installed (run without --no-packages)."; [ -n "$dry" ] || exit 1; }

# --- Build ------------------------------------------------------------------

say "Building the Bluetooth pairing agent"
run cc -std=c11 -D_GNU_SOURCE -O2 -Wall -o home/.local/bin/bluetooth-agent src/bluetooth-agent.c $(pkg-config --cflags --libs libsystemd)

# --- Links ------------------------------------------------------------------

# --no-folding keeps ~/.config/mango etc. real folders, so local.conf can sit
# beside the links. .qmlls.ini is generated by Quickshell.
stow_ignore='\.qmlls\.ini'

# config/sddm is installed as a root-owned copy below, not linked
config_ignore=(--ignore=sddm)

# Keep an existing tmux config instead of linking ours
keep_tmux=
tmux_conf="$HOME/.config/tmux/tmux.conf"
if [ -e "$tmux_conf" ] && [ "$(readlink -f "$tmux_conf")" != "$(readlink -f config/tmux/tmux.conf)" ]; then
  keep_tmux=1
  config_ignore+=(--ignore=tmux)
  say "Keeping your own ~/.config/tmux, mangifera's tmux.conf isn't linked"
fi

# Files in the way of our links. A linked parent folder counts as the
# conflict, so --backup moves the link, not files inside another repo.
conflicts=()
declare -A seen
add_conflict() {
  [ -n "${seen[$1]}" ] && return
  seen[$1]=1
  conflicts+=("$1")
}
for pkg in config home; do
  [ "$pkg" = config ] && target="$HOME/.config" || target="$HOME"
  while IFS= read -r -d '' src; do
    rel=${src#"$pkg"/}
    case "$rel" in */.qmlls.ini) continue ;; esac
    case "$pkg/$rel" in
    config/sddm/*) continue ;;
    config/tmux/*) [ -n "$keep_tmux" ] && continue ;;
    esac
    dir=$target
    linked=
    IFS=/ read -ra parts <<<"$(dirname "$rel")"
    for part in "${parts[@]}"; do
      [ "$part" = . ] && continue
      dir="$dir/$part"
      if [ -L "$dir" ]; then
        add_conflict "$dir"
        linked=1
        break
      fi
    done
    [ -n "$linked" ] && continue
    dest="$target/$rel"
    if [ -L "$dest" ]; then
      [ "$(readlink -f "$dest")" = "$(readlink -f "$src")" ] || add_conflict "$dest"
    elif [ -e "$dest" ]; then
      add_conflict "$dest"
    fi
  done < <(find "$pkg" \( -type f -o -type l \) -print0)
done

if [ ${#conflicts[@]} -gt 0 ]; then
  stash="$HOME/.mangifera-backup-$(date +%Y%m%d-%H%M%S)"
  say "Moving ${#conflicts[@]} files in the way to $stash"
  printf '      %s\n' "${conflicts[@]}"
  for f in "${conflicts[@]}"; do
    run mkdir -p "$stash/$(dirname "${f#"$HOME"/}")"
    run mv "$f" "$stash/${f#"$HOME"/}"
  done
fi

say "Linking config/ into ~/.config and home/ into ~"
run mkdir -p "$HOME/.config"
if [ -n "$dry" ]; then
  # Skipped while conflicts remain: stow would fail on them
  if [ ${#conflicts[@]} -eq 0 ] && command -v stow >/dev/null; then
    stow -n --no-folding --ignore="$stow_ignore" "${config_ignore[@]}" -t "$HOME/.config" config
    stow -n --no-folding --ignore="$stow_ignore" -t "$HOME" home
  fi
else
  stow --no-folding --ignore="$stow_ignore" "${config_ignore[@]}" -t "$HOME/.config" config
  stow --no-folding --ignore="$stow_ignore" -t "$HOME" home
fi

# --- Wallpaper ------------------------------------------------------------------

# Carry over swarch's wallpaper
old_state="${XDG_STATE_HOME:-$HOME/.local/state}/swarch/wallpaper"
new_state="${XDG_STATE_HOME:-$HOME/.local/state}/mangifera/wallpaper"
if [ -f "$old_state" ] && [ ! -e "$new_state" ]; then
  say "Keeping swarch's wallpaper"
  run mkdir -p "$(dirname "$new_state")"
  run cp "$old_state" "$new_state"
fi

# --- tmux plugins -------------------------------------------------------------

# Own tmux server, so a running one isn't touched
tpm="$HOME/.config/tmux/plugins/tpm"
if [ ! -d "$tpm" ] && { [ -z "$keep_tmux" ] || grep -q 'plugins/tpm/tpm' "$tmux_conf"; }; then
  say "Downloading tmux's plugins"
  run git clone -q --depth 1 https://github.com/tmux-plugins/tpm "$tpm"
  if [ -z "$dry" ]; then
    sock=$(mktemp -d)
    env -u TMUX TMUX_TMPDIR="$sock" "$tpm/bin/install_plugins" >/dev/null
    rm -rf "$sock"
  else
    echo "    would run: $tpm/bin/install_plugins"
  fi
fi

# --- Login screen -------------------------------------------------------------

# SDDM can't read $HOME, so the theme needs a root-owned copy
if [ -d /usr/share/sddm/themes ] || [ -n "$dry" ]; then
  say "Installing the SDDM login theme"
  run sudo rsync -a --delete --chown=root:root config/sddm/themes/custom/ /usr/share/sddm/themes/custom/
  # /etc/sddm.conf, if present, overrides this
  run sudo install -Dm644 etc/sddm.conf.d/custom-theme.conf /etc/sddm.conf.d/custom-theme.conf
  run sudo install -Dm644 etc/sddm/mango.conf /etc/sddm/mango.conf
  # Leftovers from X and swarch's sway greeter
  run sudo rm -f /etc/sddm/Xsetup /etc/sddm/sway.conf
  # ~/.local/bin/wallpaper copies the wallpaper here for SDDM
  run sudo install -d -m755 -o "$USER" -g "$(id -gn)" /var/lib/sddm-wallpaper
  if [ ! -e /var/lib/sddm-wallpaper/current ]; then
    run cp home/.local/share/mangifera/default-wallpaper.jpg /var/lib/sddm-wallpaper/current
  fi
else
  note "SDDM isn't installed, so the login theme was skipped."
fi

# --- Services ----------------------------------------------------------------

# Another login manager already enabled is left alone
if [ "$(systemctl is-enabled sddm 2>/dev/null)" != enabled ]; then
  current=$(readlink /etc/systemd/system/display-manager.service 2>/dev/null || true)
  if [ -z "$current" ]; then
    say "Enabling SDDM for the next boot"
    run sudo systemctl enable sddm
  else
    dm=$(basename "$current" .service)
    note "$dm is the login manager. To use mangifera's login screen:"
    note "  sudo systemctl disable $dm && sudo systemctl enable sddm"
  fi
fi

if [ "$(systemctl is-enabled bluetooth 2>/dev/null)" != enabled ]; then
  say "Enabling Bluetooth"
  run sudo systemctl enable --now bluetooth
fi

# Runs config/pipewire/filter-chain.conf.d, the "Noise Canceling" mic
if [ "$(systemctl --user is-enabled filter-chain 2>/dev/null)" != enabled ]; then
  say "Enabling the noise-canceling mic"
  run systemctl --user enable --now filter-chain
fi

if [ "$(xdg-mime query default inode/directory 2>/dev/null)" != thunar.desktop ]; then
  say "Making Thunar the file manager"
  run xdg-mime default thunar.desktop inode/directory
fi

# Not enabled here: switching network services could cut the connection
if [ "$(systemctl is-enabled NetworkManager 2>/dev/null)" != enabled ]; then
  note "NetworkManager isn't enabled; the bar's network panel needs it:"
  note "  sudo systemctl enable --now NetworkManager"
fi

# --- Done -----------------------------------------------------------------------

if [ -n "$dry" ]; then
  say "Dry run done: nothing was changed."
else
  say "Installed. Put your displays and other settings in"
  echo "    ~/.config/mango/local.conf, then log in to mango (or restart it)."
fi
