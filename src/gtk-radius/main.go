// gtk-radius: writes ~/.config/gtk-3.0/radius.css, adw-gtk3's corner radii
// capped at 4px. config/gtk-3.0/gtk.css imports it.
//
// Rerun it after an adw-gtk-theme update. Every radius rule is copied, 0s
// too, since gtk.css outranks the theme whatever the selector.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// The theme it reads. The tests move it
var theme = "/usr/share/themes/adw-gtk3-dark/gtk-3.0/gtk.css"

const (
	// Radii above this become this
	radius = 4
	// Radii at or above this stay (circles, pills)
	pill = 99
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gtk-radius:", err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile(theme)
	if err != nil {
		return fmt.Errorf("no %s (adw-gtk-theme)", theme)
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}
	out := filepath.Join(home, ".config/gtk-3.0/radius.css")

	rules, count := radiusRules(string(data))
	css := fmt.Sprintf("/* Generated by ~/.local/bin/gtk-radius from %s */\n\n%s", theme, rules)
	if err := writeFile(out, css); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "%d rules written to %s\n", count, out)
	return nil
}

// Writes the file whole or not at all: to a temporary file, then renamed
// over it. When it's a link (stow links it to the repo's
// config/gtk-3.0/radius.css), the file it links to is written, so the link
// stays
func writeFile(path, content string) error {
	if real, err := filepath.EvalSymlinks(path); err == nil {
		path = real
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return err
	}
	return nil
}

// CSS's white space
const space = " \t\n\r\f"

var (
	// border-radius: 6px; border-top-left-radius: 0;
	radiusDecl = regexp.MustCompile(`border(-[a-z]+)*-radius[` + space + `]*:[` + space + `]*[^;]+;`)
	pixels     = regexp.MustCompile(`[0-9]+(\.[0-9]+)?px`)
	spaces     = regexp.MustCompile(`[` + space + `]+`)
)

// The theme's rules that set a radius, with only their radius declarations,
// radii capped, and how many there are
func radiusRules(css string) (string, int) {
	if !strings.HasSuffix(css, "\n") {
		css += "\n"
	}
	css = stripComments(css)

	var rules []string
	// Each piece up to a } ends with an innermost "selector { body". The
	// piece after the last } isn't a rule
	pieces := strings.Split(css, "}")
	for _, piece := range pieces[:len(pieces)-1] {
		brace := strings.LastIndex(piece, "{")
		if brace < 0 {
			continue
		}
		body := piece[brace+1:]
		// After an outer rule's { (@media ... {)
		head := piece[:brace]
		if outer := strings.LastIndex(head, "{"); outer >= 0 {
			head = head[outer+1:]
		}
		if head == "" {
			continue
		}

		var lines strings.Builder
		for _, decl := range radiusDecl.FindAllString(body, -1) {
			name, value, _ := strings.Cut(strings.TrimSuffix(decl, ";"), ":")
			name = strings.TrimRight(name, space)
			fmt.Fprintf(&lines, "  %s: %s;\n", name, shrink(strings.Trim(value, space)))
		}
		if lines.Len() == 0 {
			continue
		}
		head = strings.Trim(spaces.ReplaceAllString(head, " "), space)
		rules = append(rules, head+" {\n"+lines.String()+"}\n")
	}
	return strings.Join(rules, "\n"), len(rules)
}

// The CSS without its /* comments */. One left open runs to the end
func stripComments(css string) string {
	var plain strings.Builder
	for {
		before, after, found := strings.Cut(css, "/*")
		plain.WriteString(before)
		if !found {
			return plain.String()
		}
		_, css, _ = strings.Cut(after, "*/")
	}
}

// "6px 6px 0 0" with radius 4: "4px 4px 0 0"
func shrink(value string) string {
	return pixels.ReplaceAllStringFunc(value, func(px string) string {
		n, _ := strconv.ParseFloat(strings.TrimSuffix(px, "px"), 64)
		if n > radius && n < pill {
			return strconv.Itoa(radius) + "px"
		}
		return px
	})
}
